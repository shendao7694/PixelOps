  /**
   * Visible teammates get only a tiny fluorescent blue diamond. A name is
   * added, without a plate or border, only for the teammate nearest the
   * reticle; visibility/proximity are supplied by the network-rate world scan.
   */
  drawTeammateMarkers(s) {
    if (!s.camera || !Array.isArray(s.teammates)
      || (s.mode !== 'playing' && s.mode !== 'dead')) return;

    for (const teammate of s.teammates) {
      if (!teammate || teammate.team !== s.player.team
        || teammate.alive === false || !teammate.visible) continue;

      this._v.set(teammate.x, teammate.y, teammate.z);
      this._cameraV.copy(this._v).applyMatrix4(s.camera.matrixWorldInverse);
      if (this._cameraV.z >= -0.05) continue;
      this._v.project(s.camera);
      if (this._v.z < -1 || this._v.z > 1
        || Math.abs(this._v.x) > 0.98 || Math.abs(this._v.y) > 0.96) continue;

      const x = Math.round((this._v.x * 0.5 + 0.5) * this.w);
      const y = Math.round((-this._v.y * 0.5 + 0.5) * this.h - 5);
      const color = '#71c7ff';

      // A soft 5x5 diamond behind a crisp 3x3 diamond creates the fluorescent
      // point without turning it into a nameplate or a solid badge.
      this.ctx.globalAlpha = 0.18;
      this.rect(x, y - 2, 1, 1, color);
      this.rect(x - 1, y - 1, 3, 1, color);
      this.rect(x - 2, y, 5, 1, color);
      this.rect(x - 1, y + 1, 3, 1, color);
      this.rect(x, y + 2, 1, 1, color);
      this.ctx.globalAlpha = 1;
      this.rect(x, y - 1, 1, 1, '#bdeaff');
      this.rect(x - 1, y, 3, 1, color);
      this.rect(x, y + 1, 1, 1, '#4fa3ff');

      if (teammate.showName) {
        const name = String(teammate.name || 'TEAMMATE').slice(0, 14);
        this.text(name, x, y - 10, {
          scale: 1,
          align: 'center',
          color: '#8ed8ff',
          shadow: false,
          localize: false,
        });
      }
      this.ctx.globalAlpha = 1;
    }
  }

