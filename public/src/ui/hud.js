      const charge = Math.max(0, Math.floor(Number(st[id]) || 0));
      const active = (id === 'uav' && Number(st.uavTime) > 0)
        || (id === 'sentry' && Number(st.sentryHp) > 0)
        || (id === 'railgun' && Boolean(st.railgunActive));
      // A second UAV charge cannot be called while the team aircraft is live.
      const available = charge > 0 && !(id === 'uav' && active);
      const frameColor = available
        ? COL.green
        : active
          ? COL.blue
          : 'rgba(134,153,166,0.42)';
