  drawDeath(s) {
    this.rect(0, 0, this.w, this.h, 'rgba(40,4,4,0.32)');
    const cy = Math.round(this.h * 0.30);
    this.text('YOU WERE KILLED', this.w / 2, cy, { scale: 3, align: 'center', color: '#ff5b4c' });
    if (s.player.killedBy) {
      this.text('BY  ' + s.player.killedBy.name, this.w / 2, cy + 26, { scale: 2, align: 'center', color: COL.text });
      if (s.player.killedByWeapon) {
        const iconW = this.h < 220 ? 42 : this.h < 400 ? 54 : 70;
        this.silhouette(
          s.player.killedByWeapon,
          this.w / 2 - iconW / 2,
          cy + 44,
          iconW,
          Math.round(iconW / 2),
          {
            alpha: 0.78,
            fallback: s.player.killedByWeapon === 'gravity' ? ICONS.gravity : null,
          }
        );
      }
    }
    // health and ammo are hidden while dead, so the bottom third is free
    const py = Math.round(this.h * 0.72);
    const t = Math.max(0, Math.ceil(s.player.respawnIn));
    if (t > 0) {
      this.text('AUTO RESPAWN IN ' + t, this.w / 2, py, { scale: 2, align: 'center', color: COL.amber });
      this.text('ENTER: CHANGE LOADOUT', this.w / 2, py + 18, {
        scale: 1, align: 'center', color: COL.dim,
      });
    } else {
      const blink = (this.time * 3) % 1 > 0.4;
      if (blink) this.text('REINFORCING...', this.w / 2, py, {
        scale: 2, align: 'center', color: COL.green,
      });
    }
  }

  drawGameOver(s) {
    this.rect(0, 0, this.w, this.h, 'rgba(4,7,11,0.86)');
    const scale = this.h < 220 ? 4 : 5;
    const cy = Math.round(this.h * 0.22);
    const won = s.match.winner === s.player.team;
    this.text(won ? 'VICTORY' : 'DEFEAT', this.w / 2, cy, {
      scale, align: 'center', color: won ? COL.green : COL.red,
    });
    this.text(won ? 'ENEMY TEAM ELIMINATED' : 'YOUR TEAM ELIMINATED', this.w / 2, cy + scale * 7 + 9, {
      scale: 1, align: 'center', color: COL.dim,
    });
    const stats = [
      ['KILLS', s.score.kills],
      ['DEATHS', s.score.deaths],
      ['SCORE', s.score.total],
    ];
    // the button is bottom-anchored, so a short screen shrinks the gap above
    // it rather than pushing it off the bottom
    const btnY = this.h - 30;
    let sy = Math.min(cy + scale * 7 + 27, btnY - 10 - stats.length * 11);
    for (const [k, v] of stats) {
      this.text(k, this.w / 2 - 8, sy, { scale: 1, align: 'right', color: COL.dim });
      this.text(String(v), this.w / 2 + 8, sy, { scale: 1, align: 'left', color: COL.text });
      sy += 11;
    }
    this.button('restart', this.w / 2 - 55, btnY, 110, 18, 'PLAY AGAIN', { scale: 2 });
  }

  /** Hit test for menu clicks; pointer is normalised 0..1. */
  pick(nx, ny) {
    const x = nx * this.w;
    const y = ny * this.h;
    for (const b of this.buttons) {
      if (x >= b.x && x <= b.x + b.w && y >= b.y && y <= b.y + b.h) return b.id;
    }
    return null;
  }
