export function scopeRecoilPose(width, height, recoil = 0) {
  const kick = clamp(Number(recoil) || 0, 0, 2);
  const baseRadius = Math.min(width, height) * 0.42;
  return {
    cx: width / 2,
    // The optic rises with the shot while its black mask/lens grows toward
    // the player, then both ease back as ViewModel's recoil envelope decays.
    cy: height / 2 - Math.min(16, height * 0.035) * kick,
    r: baseRadius * (1 + 0.075 * kick),
  };
}

