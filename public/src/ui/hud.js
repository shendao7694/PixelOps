    // The wider shared silhouettes share the metadata row, never the magazine
    // row. On the smallest HUD the art contracts slightly so the combined
    // name + silhouette group stays out of the central combat-feedback lane.
    const iconY = h - 58 - iconH;
    const metaTextX = iconX - 5;
    const metaTextInset = Math.max(0, Math.floor((iconH - 15) / 2));
