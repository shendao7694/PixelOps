  drawCompass(s) {
    const w = 160;
    const x0 = Math.round(this.w / 2 - w / 2);
    const y = 6;
    this.rect(x0, y, w, 11, 'rgba(4,8,12,0.45)');
    this.frame(x0, y, w, 11, 'rgba(140,160,180,0.25)');
    const yaw = s.yaw;
    // yaw 0 faces -Z (north); convert to degrees running clockwise
    const heading = ((-yaw * 180 / Math.PI) % 360 + 360) % 360;
    const pxPerDeg = w / 180;
    const marks = [
      [0, 'N'], [45, 'NE'], [90, 'E'], [135, 'SE'], [180, 'S'], [225, 'SW'], [270, 'W'], [315, 'NW'],
    ];
    for (const [deg, label] of marks) {
      let d = deg - heading;
      while (d > 180) d -= 360;
      while (d < -180) d += 360;
      const px = this.w / 2 + d * pxPerDeg;
      if (px < x0 + 4 || px > x0 + w - 4) continue;
      this.rect(px, y + 1, 1, 3, COL.text);
      this.text(label, px, y + 5, { scale: 1, align: 'center', color: label.length === 1 ? COL.text : COL.dim });
    }
    for (let deg = 0; deg < 360; deg += 15) {
      if (deg % 45 === 0) continue;
      let d = deg - heading;
      while (d > 180) d -= 360;
      while (d < -180) d += 360;
      const px = this.w / 2 + d * pxPerDeg;
      if (px < x0 + 2 || px > x0 + w - 2) continue;
      this.rect(px, y + 1, 1, 2, 'rgba(200,216,228,0.35)');
    }
    this.rect(this.w / 2, y + 9, 1, 3, COL.amber);
    this.text(String(Math.round(heading)).padStart(3, '0'), this.w / 2, y + 13, {
      scale: 1, align: 'center', color: COL.amber,
    });
  }

