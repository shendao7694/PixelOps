  /** Project every live hostile soldier into a compact screen-space red box. */
  drawMissileTargets(s) {
    const camera = s.camera;
    const targets = s.missileCam?.targets;
    if (!camera || !Array.isArray(targets) || !targets.length) return;
    camera.updateMatrixWorld(true);

    // Horizontal extents use camera-right rather than world X, so the box
    // keeps surrounding the soldier while the missile banks and turns.
    this._cameraV.setFromMatrixColumn(camera.matrixWorld, 0).normalize();
    const rightX = this._cameraV.x;
    const rightY = this._cameraV.y;
    const rightZ = this._cameraV.z;

    for (const target of targets) {
      const x = Number(target?.x);
      const y = Number(target?.y);
      const z = Number(target?.z);
      if (![x, y, z].every(Number.isFinite)) continue;
      const height = clamp(Number(target.height) || 1.9, 0.65, 2.4);
      const radius = clamp(Number(target.radius) || 0.46, 0.25, 0.9);
      const centerY = y + height * 0.5;

      this._v.set(x, centerY, z).applyMatrix4(camera.matrixWorldInverse);
      if (this._v.z >= -Math.max(0.05, camera.near || 0.05)) continue;

      this._v.set(x, centerY, z).project(camera);
      if (this._v.z < -1 || this._v.z > 1
        || Math.abs(this._v.x) > 1.04 || Math.abs(this._v.y) > 1.04) continue;
      const centerX = (this._v.x * 0.5 + 0.5) * this.w;
      const centerScreenY = (-this._v.y * 0.5 + 0.5) * this.h;

      this._v.set(x, y, z).project(camera);
      const bottomY = (-this._v.y * 0.5 + 0.5) * this.h;
      this._v.set(x, y + height, z).project(camera);
      const topY = (-this._v.y * 0.5 + 0.5) * this.h;
      this._v.set(
        x + rightX * radius,
        centerY + rightY * radius,
        z + rightZ * radius
      ).project(camera);
      const rightScreenX = (this._v.x * 0.5 + 0.5) * this.w;
      this._v.set(
        x - rightX * radius,
        centerY - rightY * radius,
        z - rightZ * radius
      ).project(camera);
      const leftScreenX = (this._v.x * 0.5 + 0.5) * this.w;

      const minSize = this.h <= 180 ? 8 : 10;
      const maxWidth = Math.max(minSize, Math.min(48, Math.round(this.w * 0.08)));
      const maxHeight = Math.max(minSize, Math.min(56, Math.round(this.h * 0.13)));
      const boxW = clamp(Math.round(Math.abs(rightScreenX - leftScreenX) + 4), minSize, maxWidth);
      const boxH = clamp(Math.round(Math.abs(bottomY - topY) + 4), minSize, maxHeight);
      const x0 = clamp(Math.round(centerX - boxW * 0.5), 2, Math.max(2, this.w - boxW - 2));
      const y0 = clamp(Math.round(centerScreenY - boxH * 0.5), 2, Math.max(2, this.h - boxH - 2));

      this.frame(x0 - 1, y0 - 1, boxW + 2, boxH + 2, 'rgba(0,0,0,0.84)');
      this.frame(x0, y0, boxW, boxH, COL.red);
    }
  }

  drawScope(s) {
    if (s.weapon?.squareScope) {
      this.drawSquareScope(s);
      return;
    }
    const { cx, cy, r } = scopeRecoilPose(
      this.w,
      this.h,
      s.weapon?.scopeRecoil
    );
    const ctx = this.ctx;
    // black-out corners with rectangles (kept chunky on purpose)
    ctx.fillStyle = '#05070a';
    for (let y = 0; y < this.h; y++) {
      const dy = y - cy;
      if (Math.abs(dy) > r) { ctx.fillRect(0, y, this.w, 1); continue; }
      const half = Math.sqrt(r * r - dy * dy);
      ctx.fillRect(0, y, Math.max(0, Math.floor(cx - half)), 1);
      const rx = Math.ceil(cx + half);
      ctx.fillRect(rx, y, this.w - rx, 1);
    }
    // reticle
    this.rect(cx - r + 6, cy, r * 2 - 12, 1, 'rgba(20,26,20,0.9)');
    this.rect(cx, cy - r + 6, 1, r * 2 - 12, 'rgba(20,26,20,0.9)');
    this.rect(cx - 12, cy, 24, 1, '#0b120c');
    this.rect(cx, cy - 12, 1, 24, '#0b120c');
    for (let i = 1; i <= 4; i++) {
      this.rect(cx - 2, cy + i * 8, 5, 1, '#0b120c');
      this.rect(cx - 1, cy - i * 8, 3, 1, '#0b120c');
      this.rect(cx + i * 8, cy - 1, 1, 3, '#0b120c');
      this.rect(cx - i * 8, cy - 1, 1, 3, '#0b120c');
    }
    this.rect(cx, cy, 1, 1, '#0b120c');
    // glare
    this.ctx.globalAlpha = 0.10;
    this.rect(cx - r * 0.7, cy - r * 0.62, r * 0.8, 2, '#ffffff');
    this.ctx.globalAlpha = 1;
  }

  /**
   * The ARC-7 railgun's box optic: a hard square cut-out instead of the
   * round lens, red EM reticle furniture inside. The mask rises and grows
   * with the same recoil envelope as the round scope.
   */
  drawSquareScope(s) {
    const recoil = clamp(Number(s.weapon?.scopeRecoil) || 0, 0, 2);
    const cx = Math.round(this.w / 2);
    const cy = Math.round(this.h / 2 - Math.min(16, this.h * 0.035) * recoil);
    const half = Math.round(Math.min(this.w, this.h) * 0.40 * (1 + 0.06 * recoil));
    const ctx = this.ctx;
    // black-out everything outside the square aperture
    ctx.fillStyle = '#05070a';
    ctx.fillRect(0, 0, this.w, cy - half);
    ctx.fillRect(0, cy + half, this.w, this.h - cy - half);
    ctx.fillRect(0, cy - half, cx - half, half * 2);
    ctx.fillRect(cx + half, cy - half, this.w - cx - half, half * 2);
    // chunky double frame, machine-black outside, deep EM red inside
    this.frame(cx - half - 3, cy - half - 3, half * 2 + 6, half * 2 + 6, 'rgba(0,0,0,0.92)');
    this.frame(cx - half - 1, cy - half - 1, half * 2 + 2, half * 2 + 2, '#3d0f0c');
    // corner brackets (EM targeting furniture)
    const arm = Math.max(10, Math.round(half * 0.22));
    const red = '#ff4030';
    const dimRed = 'rgba(150,30,22,0.9)';
    for (const [bx, by, sx, sy] of [
      [cx - half + 4, cy - half + 4, 1, 1],
      [cx + half - 4, cy - half + 4, -1, 1],
      [cx - half + 4, cy + half - 4, 1, -1],
      [cx + half - 4, cy + half - 4, -1, -1],
    ]) {
      this.rect(Math.min(bx, bx + sx * arm), by - 1, arm, 2, red);
      this.rect(bx - 1, Math.min(by, by + sy * arm), 2, arm, red);
    }
    // reticle: thin full-span cross, broken at the centre bracket
    this.rect(cx - half + 6, cy, half * 2 - 12, 1, dimRed);
    this.rect(cx, cy - half + 6, 1, half * 2 - 12, dimRed);
    this.rect(cx - 14, cy, 10, 1, red);
    this.rect(cx + 4, cy, 10, 1, red);
    this.rect(cx, cy - 14, 1, 10, red);
    this.rect(cx, cy + 4, 1, 10, red);
    // rangefinder ticks down the vertical stadia
    for (let i = 1; i <= 4; i++) {
      this.rect(cx - 4, cy + i * 12, 8, 1, red);
      this.rect(cx - 2, cy - i * 12, 4, 1, dimRed);
    }
    this.rect(cx, cy, 1, 1, red);
    // One-second hold-to-fire meter. It sits immediately below the reticle so
    // the operator can keep both the target and charge state in one glance.
    const charge = clamp(Number(s.weapon?.chargeProgress) || 0, 0, 1);
    const chargeW = Math.max(44, Math.round(half * 0.72));
    const chargeX = Math.round(cx - chargeW / 2);
    const chargeY = cy + 20;
    this.rect(chargeX - 2, chargeY - 2, chargeW + 4, 7, 'rgba(0,0,0,0.78)');
    this.frame(
      chargeX - 1,
      chargeY - 1,
      chargeW + 2,
      5,
      charge >= 1 ? '#fff0e8' : dimRed
    );
    this.rect(
      chargeX,
      chargeY,
      Math.round(chargeW * charge),
      3,
      charge >= 1 ? '#fff0e8' : red
    );
    // charge readout flavour, top-left inside the aperture
    this.text('ARC-7 // THERMAL LINK', cx - half + 8, cy - half + 6, { scale: 1, color: dimRed });
    // faint lens glare
    this.ctx.globalAlpha = 0.08;
    this.rect(cx - half * 0.7, cy - half * 0.62, half * 0.9, 2, '#ffffff');
    this.ctx.globalAlpha = 1;
  }

