  /**
   * Draw one of the shared transparent raster/vector silhouettes into a fixed HUD box.
   * The artwork is preloaded once and aspect-fitted here; the old tiny pixel
   * glyphs remain only as a first-frame/headless fallback.
   */
  silhouette(id, x, y, w, h, {
    alpha = 1,
    fallback = null,
  } = {}) {
    const safeW = Math.max(1, Math.round(w));
    const safeH = Math.max(1, Math.round(h));
    const image = canvasSilhouetteImage(id);
    const previousAlpha = this.ctx.globalAlpha;
    const previousSmoothing = this.ctx.imageSmoothingEnabled;
    this.ctx.globalAlpha = previousAlpha * clamp(alpha, 0, 1);

    if (image?.complete && Number(image.naturalWidth) > 0
      && Number(image.naturalHeight) > 0) {
      const scale = Math.min(
        safeW / image.naturalWidth,
        safeH / image.naturalHeight
      );
      const drawW = Math.max(1, Math.round(image.naturalWidth * scale));
      const drawH = Math.max(1, Math.round(image.naturalHeight * scale));
      const drawX = Math.round(x + (safeW - drawW) / 2);
      const drawY = Math.round(y + (safeH - drawH) / 2);
      // Smooth the single downscale into the low-resolution HUD. The complete
      // HUD canvas is still enlarged with nearest-neighbour sampling later.
      this.ctx.imageSmoothingEnabled = true;
      this.ctx.drawImage(image, drawX, drawY, drawW, drawH);
    } else {
      const rows = fallback || fallbackIcon(id);
      const spriteW = rows[0].length;
      const spriteH = rows.length;
      const scale = Math.max(1, Math.floor(Math.min(safeW / spriteW, safeH / spriteH)));
      this.sprite(
        rows,
        Math.round(x + (safeW - spriteW * scale) / 2),
        Math.round(y + (safeH - spriteH * scale) / 2),
        scale,
        COL.text
      );
    }

    this.ctx.imageSmoothingEnabled = previousSmoothing;
    this.ctx.globalAlpha = previousAlpha;
  }

  /** Live WebSocket round-trip time, shown only while an online PVP match exists. */
