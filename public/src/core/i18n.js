export function normalizeLanguage(value) {
  return value === 'zh' || value === 'zh-CN' ? 'zh-CN' : DEFAULT_LANGUAGE;
}

export function isChineseLanguage(language) {
  return normalizeLanguage(language) === 'zh-CN';
}

export function localizeText(value, language = DEFAULT_LANGUAGE) {
  const source = String(value ?? '');
  if (!source || !isChineseLanguage(language)) return source;
  if (Object.prototype.hasOwnProperty.call(ZH, source)) return ZH[source];
  for (const [pattern, replace] of ZH_PATTERNS) {
    const match = source.match(pattern);
    if (match) return replace(match);
  }
  if (source.includes('  //  ')) {
    return source
      .split('  //  ')
      .map((part) => localizeText(part, 'zh-CN'))
      .join('  //  ');
  }
  if (source.includes(' // ')) {
    return source
      .split(' // ')
      .map((part) => localizeText(part, 'zh-CN'))
      .join(' // ');
  }
  return source;
}

export function applyDocumentLanguage(language, doc = globalThis.document) {
  const normalized = normalizeLanguage(language);
  if (doc?.documentElement) {
    doc.documentElement.lang = normalized;
    doc.documentElement.dataset.language = normalized;
  }
  return normalized;
}
